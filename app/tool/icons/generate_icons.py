#!/usr/bin/env python3
"""Builds every app-icon file from the SVGs in tool/icons/svg.

  pip install cairosvg pillow
  python3 tool/icons/generate_icons.py

Writes the default launcher icons for each platform plus the alternate icons
the user can pick in Settings -> App icon. The list of icons must match
lib/services/app_icon.dart (a test checks it).
"""
import io
import json
import os
import re
import shutil

import cairosvg
from PIL import Image

APP = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SVG = os.path.join(APP, 'tool', 'icons', 'svg')
DEFAULT = 'play_r'

ICONS = sorted(f[:-4] for f in os.listdir(SVG) if f.endswith('.svg'))  # "12_play_r"
def ident(name): return name.split('_', 1)[1]                          # "play_r"
def camel(i): return ''.join(p.capitalize() for p in i.split('_'))     # "PlayR"


def svg_text(name): return open(os.path.join(SVG, name + '.svg')).read()


def rounded(name):
    """Rounded-square artwork with transparent corners."""
    return svg_text(name)


def full_bleed(name, pad=0):
    """Square artwork with no rounding; [pad] extends the background outward
    (used for Android adaptive icons, which crop the edges)."""
    s = svg_text(name).replace('<g clip-path="url(#clip)">', '<g>')
    s = s.replace('<rect width="1024" height="1024" fill="url(#bg)"/>',
                  '<rect x="-400" y="-400" width="1824" height="1824" fill="url(#bg)"/>')
    if pad:
        s = s.replace('viewBox="0 0 1024 1024"', f'viewBox="{-pad} {-pad} {1024 + 2 * pad} {1024 + 2 * pad}"')
    return s


def padded(name, pad):
    """Rounded artwork inset in a transparent square (macOS icon grid)."""
    return svg_text(name).replace('viewBox="0 0 1024 1024"', f'viewBox="{-pad} {-pad} {1024 + 2 * pad} {1024 + 2 * pad}"')


def png(svg, size, path, opaque=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)
    img = Image.open(io.BytesIO(data))
    if opaque:  # iOS rejects icons with an alpha channel
        img = img.convert('RGB')
    img.save(path, optimize=True)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write(text)


default = next(n for n in ICONS if ident(n) == DEFAULT)

# ---- Flutter assets: previews for Settings, and the desktop window icon ----
for n in ICONS:
    png(rounded(n), 256, f'{APP}/assets/app_icons/{ident(n)}.png')

# ---- Android ----
res = f'{APP}/android/app/src/main/res'
# Adaptive icons crop to the centre ~2/3, so the 1024 artwork is drawn into an
# 76/108 area of the canvas with its background extended to the edges.
ADAPTIVE_PAD = round(1024 * (108 / 76 - 1) / 2)
for n in ICONS:
    i = ident(n)
    png(full_bleed(n, ADAPTIVE_PAD), 432, f'{res}/drawable-nodpi/ic_icon_{i}_bg.png')
    write(f'{res}/mipmap-anydpi-v26/ic_icon_{i}.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_icon_{i}_bg"/>
    <foreground android:drawable="@android:color/transparent"/>
</adaptive-icon>
''')
    png(rounded(n), 192, f'{res}/mipmap-xxxhdpi/ic_icon_{i}.png')
write(f'{res}/mipmap-anydpi-v26/ic_launcher.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_icon_{DEFAULT}_bg"/>
    <foreground android:drawable="@android:color/transparent"/>
</adaptive-icon>
''')
for d, s in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
    png(rounded(default), s, f'{res}/mipmap-{d}/ic_launcher.png')

# Launcher aliases, one per icon (MainActivity itself only carries the TV entry).
aliases = '\n'.join(f'''        <activity-alias
            android:name=".Icon{camel(ident(n))}"
            android:targetActivity=".MainActivity"
            android:label="RomRunner"
            android:icon="@mipmap/ic_icon_{ident(n)}"
            android:enabled="{'true' if n == default else 'false'}"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN"/>
                <category android:name="android.intent.category.LAUNCHER"/>
            </intent-filter>
        </activity-alias>''' for n in ICONS)
manifest = f'{APP}/android/app/src/main/AndroidManifest.xml'
m = open(manifest).read()
block = f'        <!-- app-icons:begin (generated by tool/icons/generate_icons.py) -->\n{aliases}\n        <!-- app-icons:end -->'
if '<!-- app-icons:begin' in m:
    m = re.sub(r'        <!-- app-icons:begin.*?<!-- app-icons:end -->', lambda _: block, m, flags=re.S)
else:
    m = m.replace('        <!-- Don\'t delete the meta-data below.', block + '\n        <!-- Don\'t delete the meta-data below.', 1)
open(manifest, 'w').write(m)

# ---- iOS: primary AppIcon plus one alternate set per icon ----
xc = f'{APP}/ios/Runner/Assets.xcassets'
def ios_set(dirname, name):
    d = f'{xc}/{dirname}.appiconset'
    shutil.rmtree(d, ignore_errors=True)
    png(full_bleed(name), 1024, f'{d}/icon-1024.png', opaque=True)
    write(f'{d}/Contents.json', json.dumps({
        'images': [{'filename': 'icon-1024.png', 'idiom': 'universal', 'platform': 'ios', 'size': '1024x1024'}],
        'info': {'author': 'xcode', 'version': 1},
    }, indent=2) + '\n')
ios_set('AppIcon', default)
for n in ICONS:
    if n != default:
        ios_set(f'AppIcon-{camel(ident(n))}', n)

# ---- macOS ----
mac = f'{APP}/macos/Runner/Assets.xcassets/AppIcon.appiconset'
for s in [16, 32, 64, 128, 256, 512, 1024]:
    png(padded(default, 100), s, f'{mac}/app_icon_{s}.png')

# ---- Windows ----
ico = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=rounded(default).encode(), output_width=256, output_height=256)))
ico.save(f'{APP}/windows/runner/resources/app_icon.ico', sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])

# ---- Web ----
png(rounded(default), 32, f'{APP}/web/favicon.png')
png(rounded(default), 192, f'{APP}/web/icons/Icon-192.png')
png(rounded(default), 512, f'{APP}/web/icons/Icon-512.png')
png(full_bleed(default, ADAPTIVE_PAD), 192, f'{APP}/web/icons/Icon-maskable-192.png')
png(full_bleed(default, ADAPTIVE_PAD), 512, f'{APP}/web/icons/Icon-maskable-512.png')

print('icons:', ', '.join(ident(n) for n in ICONS), '| default:', DEFAULT)
